#!/usr/bin/env python3
"""Generate crates/moc-civ/src/ages_table.rs from data/ages.json (#69).

The age ladder is data (docs/ages.md). The wasm build must not carry a JSON parser, so this
script turns the JSON into a static Rust table, checked in next to the code that reads it.

    python crates/moc-civ/gen_ages.py           # rewrite the table
    python crates/moc-civ/gen_ages.py --check   # exit 1 if the table is out of date

`cargo test -p moc-civ` also fails when data/ages.json changes without a rerun: the table
records a hash of the JSON (FNV-1a over its bytes with carriage returns dropped).
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "ages.json"
OUT = Path(__file__).resolve().parent / "src" / "ages_table.rs"


def fnv1a(data: bytes) -> int:
    h = 0xCBF29CE484222325
    for b in data:
        if b == 0x0D:  # same hash whatever the checkout's line endings
            continue
        h ^= b
        h = (h * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def camel(key: str) -> str:
    return "".join(p[:1].upper() + p[1:] for p in re.split(r"[^A-Za-z0-9]+", key) if p)


def rs_str(s: str) -> str:
    return json.dumps(s, ensure_ascii=False)


def f32(v) -> str:
    v = float(v)
    return f"{v:.1f}" if v == int(v) else repr(v)


def age_range(text: str, what: str, last: int):
    """'clan feuds (ages 1-6)' -> (1, 6); 'succession splits (age 7+)' -> (7, last)."""
    m = re.search(r"\(ages?\s+(\d+)\s*(?:[-–]\s*(\d+)|\+)\)", text)
    if not m:
        sys.exit(f"gen_ages: no age range in {what}: {text!r}")
    lo = int(m.group(1))
    hi = int(m.group(2)) if m.group(2) else last
    return lo, hi


def first_age(text: str, what: str) -> int:
    m = re.search(r"\bages?\s+(\d+)", text)
    if not m:
        sys.exit(f"gen_ages: no age number in {what}: {text!r}")
    return int(m.group(1))


def cond_list(d: dict, metrics: list) -> str:
    out = []
    for k, v in d.items():
        if k not in metrics:
            sys.exit(f"gen_ages: unknown metric {k!r} in an entry condition")
        val = 1.0 if v is True else 0.0 if v is False else v
        out.append(f"Cond {{ metric: Metric::{camel(k)}, at_least: {f32(val)} }}")
    return "&[" + ", ".join(out) + "]"


def generate(raw: bytes) -> str:
    data = json.loads(raw.decode("utf-8"))
    metrics = list(data["metrics"].keys())
    ages = data["ages"]
    assert [a["n"] for a in ages] == list(range(1, len(ages) + 1)), "ages must be numbered 1..N in order"

    jobs, buildings = [], []  # (key, first age), in order of first appearance
    for a in ages:
        for j in a["jobs"]:
            if j not in [k for k, _ in jobs]:
                jobs.append((j, a["n"]))
        for b in a["buildings"]:
            if b not in [k for k, _ in buildings]:
                buildings.append((b, a["n"]))
    assert len(buildings) <= 64, "Building fits a u64 mask"

    col = data["collapse"]
    con = data["conflict"]
    bat = con["battle"]
    esc = con["escalation"]
    war = next(e for e in esc if e["level"] == "war")

    L = []
    w = L.append
    w("// @generated by crates/moc-civ/gen_ages.py from data/ages.json. Do not edit by hand:")
    w("// change the JSON and rerun `python crates/moc-civ/gen_ages.py`.")
    w("#![allow(clippy::all)]")
    w("")
    w("/// FNV-1a of data/ages.json (carriage returns dropped) when this table was generated.")
    w(f"pub const SOURCE_FNV: u64 = 0x{fnv1a(raw):016x};")
    w("")
    w("/// The simulation metrics of `data/ages.json` (`metrics`), in file order.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("#[repr(u8)]")
    w("pub enum Metric {")
    for k in metrics:
        w(f"    /// {data['metrics'][k]}")
        w(f"    {camel(k)},")
    w("}")
    w("")
    w("impl Metric {")
    w(f"    pub const ALL: [Metric; {len(metrics)}] = [{', '.join('Metric::' + camel(k) for k in metrics)}];")
    w("    pub fn key(self) -> &'static str {")
    w("        match self {")
    for k in metrics:
        w(f"            Metric::{camel(k)} => {rs_str(k)},")
    w("        }")
    w("    }")
    w("}")
    w("")

    def enum(name, items, doc):
        w(f"/// {doc}")
        w("#[derive(Clone, Copy, Debug, PartialEq, Eq, PartialOrd, Ord, Hash)]")
        w("#[repr(u8)]")
        w(f"pub enum {name} {{")
        for i, (k, n) in enumerate(items):
            w(f"    /// `{k}`, from age {n}.")
            w(f"    {camel(k)} = {i},")
        w("}")
        w("")
        w(f"impl {name} {{")
        w(f"    pub const COUNT: usize = {len(items)};")
        w(f"    pub const ALL: [{name}; {len(items)}] = [{', '.join(name + '::' + camel(k) for k, _ in items)}];")
        w("    /// The key in data/ages.json.")
        w("    pub fn key(self) -> &'static str {")
        w(f"        const K: [&str; {len(items)}] = [{', '.join(rs_str(k) for k, _ in items)}];")
        w("        K[self as usize]")
        w("    }")
        w("    /// The first age that lists it.")
        w("    pub fn unlock_age(self) -> u8 {")
        w(f"        const A: [u8; {len(items)}] = [{', '.join(str(n) for _, n in items)}];")
        w("        A[self as usize]")
        w("    }")
        w("}")
        w("")

    enum("Job", jobs, "Every job of the ladder, in order of first appearance (cumulative: later ages keep the earlier jobs).")
    enum("Building", buildings, "Every building of the ladder, in order of first appearance.")

    w("/// An entry condition: `metric` at least `at_least` (true/false metrics count as 1/0).")
    w("#[derive(Clone, Copy, Debug, PartialEq)]")
    w("pub struct Cond {")
    w("    pub metric: Metric,")
    w("    pub at_least: f32,")
    w("}")
    w("")
    w("#[derive(Clone, Copy, Debug, PartialEq)]")
    w("pub struct Weapon {")
    w("    pub name: &'static str,")
    w("    pub power: f32,")
    w("    /// In the data's units; combat turns it into a reach in tiles.")
    w("    pub range: f32,")
    w("}")
    w("")
    w("/// One age of the ladder. Entered when every `all` condition holds and, if `any` is not")
    w("/// empty, every condition of at least one `any` group.")
    w("#[derive(Clone, Copy, Debug)]")
    w("pub struct AgeDef {")
    w("    pub n: u8,")
    w("    pub key: &'static str,")
    w("    pub name: &'static str,")
    w("    pub all: &'static [Cond],")
    w("    pub any: &'static [&'static [Cond]],")
    w("    pub jobs: &'static [Job],")
    w("    pub buildings: &'static [Building],")
    w("    pub systems: &'static [&'static str],")
    w("    pub crises: &'static [&'static str],")
    w("    pub brain: &'static str,")
    w("    pub weapon: Weapon,")
    w("}")
    w("")
    w(f"pub const AGE_COUNT: usize = {len(ages)};")
    w("")
    w(f"pub static AGES: [AgeDef; {len(ages)}] = [")
    for a in ages:
        enter = a.get("enter", {})
        unknown = set(enter) - {"all", "any"}
        if unknown:
            sys.exit(f"gen_ages: age {a['n']}: unknown entry keys {unknown}")
        all_c = cond_list(enter.get("all", {}), metrics)
        any_c = "&[" + ", ".join(cond_list(g, metrics) for g in enter.get("any", [])) + "]"
        wp = a["weapon"]
        w("    AgeDef {")
        w(f"        n: {a['n']},")
        w(f"        key: {rs_str(a['key'])},")
        w(f"        name: {rs_str(a['name'])},")
        w(f"        all: {all_c},")
        w(f"        any: {any_c},")
        w(f"        jobs: &[{', '.join('Job::' + camel(j) for j in a['jobs'])}],")
        w(f"        buildings: &[{', '.join('Building::' + camel(b) for b in a['buildings'])}],")
        w(f"        systems: &[{', '.join(rs_str(s) for s in a['systems'])}],")
        w(f"        crises: &[{', '.join(rs_str(s) for s in a['crises'])}],")
        w(f"        brain: {rs_str(a['brain'])},")
        w(f"        weapon: Weapon {{ name: {rs_str(wp['name'])}, power: {f32(wp['power'])}, range: {f32(wp['range'])} }},")
        w("    },")
    w("];")
    w("")
    w("/// `collapse`: a civilisation falls back one age when stability stays below")
    w("/// `COLLAPSE_STABILITY_BELOW` for `COLLAPSE_FOR_SECONDS`, or its population drops below")
    w("/// `COLLAPSE_POP_SHARE` of the age's entry population.")
    w(f"pub const COLLAPSE_STABILITY_BELOW: f32 = {f32(col['stability_below'])};")
    w(f"pub const COLLAPSE_FOR_SECONDS: f32 = {f32(col['for_seconds'])};")
    w(f"pub const COLLAPSE_POP_SHARE: f32 = {f32(col['population_below_entry_share'])};")
    w("")
    w("/// `conflict.escalation`, lowest first.")
    w(f"pub const ESCALATION: [&str; {len(esc)}] = [{', '.join(rs_str(e['level']) for e in esc)}];")
    w(f"/// War between civilisations needs a declaration from this age (`escalation.war.from`).")
    w(f"pub const WAR_FROM_AGE: u8 = {first_age(war['from'], 'escalation.war.from')};")
    w("")
    w("/// `conflict.battle.terrain`: how much harder a defender is to hurt.")
    w("pub mod terrain_mul {")
    for k, v in bat["terrain"].items():
        w(f"    pub const {re.sub(r'[^A-Z0-9]', '_', k.upper())}: f32 = {f32(v)};")
    w("}")
    w("")
    w("/// Armies hold formations from this age (`conflict.battle.formations`).")
    w(f"pub const FORMATIONS_FROM_AGE: u8 = {first_age(bat['formations'], 'battle.formations')};")
    w("/// Healers mend the wounded from this age (`conflict.battle.wounds`).")
    w(f"pub const HEALERS_FROM_AGE: u8 = {first_age(bat['wounds'], 'battle.wounds')};")
    w("")
    w("/// `conflict.inside_one_civ`: the fights a civilisation has with itself, by age.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub struct InsideFight {")
    w("    pub what: &'static str,")
    w("    pub from_age: u8,")
    w("    pub to_age: u8,")
    w("}")
    w("")
    inside = con["inside_one_civ"]
    w(f"pub static INSIDE_ONE_CIV: [InsideFight; {len(inside)}] = [")
    for s in inside:
        lo, hi = age_range(s, "inside_one_civ", len(ages))
        what = re.sub(r"\s*\(.*\)\s*$", "", s)
        w(f"    InsideFight {{ what: {rs_str(what)}, from_age: {lo}, to_age: {hi} }},")
    w("];")
    w("")
    crises = []
    for a in ages:
        for c in a["crises"]:
            if c not in crises:
                crises.append(c)
    w("/// Every crisis key of the ladder (event `extra` indexes this).")
    w(f"pub static CRISES: [&str; {len(crises)}] = [{', '.join(rs_str(c) for c in crises)}];")
    w("")
    w(f"pub static DAILY_LIFE: [&str; {len(data['daily_life'])}] = [{', '.join(rs_str(s) for s in data['daily_life'])}];")
    return "\n".join(L) + "\n"


def main():
    raw = SRC.read_bytes()
    text = generate(raw)
    if "--check" in sys.argv:
        cur = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if cur.replace("\r", "") != text:
            print(f"{OUT.relative_to(ROOT)} is out of date: run python crates/moc-civ/gen_ages.py")
            sys.exit(1)
        print("ages table up to date")
        return
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
